CREATE OR REPLACE PROCEDURE borrow_book(
    p_reader_id INTEGER,
    p_book_copy_id INTEGER,
    p_employee_id INTEGER,
    p_due_at TIMESTAMP
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_due_at <= CURRENT_TIMESTAMP THEN
        RAISE EXCEPTION
            'Дата повернення повинна бути пізніше поточної дати';
    END IF;

    INSERT INTO loans (
        reader_id,
        book_copy_id,
        issued_by_employee_id,
        loaned_at,
        due_at
    )
    VALUES (
        p_reader_id,
        p_book_copy_id,
        p_employee_id,
        CURRENT_TIMESTAMP,
        p_due_at
    );
END;
$$;

CREATE OR REPLACE PROCEDURE return_book(
    p_loan_id INTEGER,
    p_employee_id INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_returned_at TIMESTAMP;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM employees
        WHERE id = p_employee_id
          AND is_deleted = false
    ) THEN
        RAISE EXCEPTION
            'Активного працівника з id % не знайдено',
            p_employee_id;
    END IF;

    SELECT returned_at
    INTO v_returned_at
    FROM loans
    WHERE id = p_loan_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Видачу з id % не знайдено',
            p_loan_id;
    END IF;

    IF v_returned_at IS NOT NULL THEN
        RAISE EXCEPTION
            'Книга за видачею id % вже була повернена',
            p_loan_id;
    END IF;

    UPDATE loans
    SET
        returned_by_employee_id = p_employee_id,
        returned_at = CURRENT_TIMESTAMP
    WHERE id = p_loan_id;
END;
$$;


