CREATE OR REPLACE FUNCTION validate_loan_before_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_copy_status VARCHAR(30);
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM readers
        WHERE id = NEW.reader_id
          AND is_deleted = false
    ) THEN
        RAISE EXCEPTION
            'Активного читача з id % не знайдено',
            NEW.reader_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM employees
        WHERE id = NEW.issued_by_employee_id
          AND is_deleted = false
    ) THEN
        RAISE EXCEPTION
            'Активного працівника з id % не знайдено',
            NEW.issued_by_employee_id;
    END IF;

    SELECT bc.status
    INTO v_copy_status
    FROM book_copies bc
    JOIN books b ON b.id = bc.book_id
    JOIN branches br ON br.id = bc.branch_id
    WHERE bc.id = NEW.book_copy_id
      AND b.is_deleted = false
      AND br.is_deleted = false
    FOR UPDATE OF bc;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Примірник книги з id % не знайдено або він недоступний',
            NEW.book_copy_id;
    END IF;

    IF v_copy_status <> 'available' THEN
        RAISE EXCEPTION
            'Примірник книги з id % недоступний. Статус: %',
            NEW.book_copy_id,
            v_copy_status;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM loans
        WHERE book_copy_id = NEW.book_copy_id
          AND returned_at IS NULL
    ) THEN
        RAISE EXCEPTION
            'Примірник книги з id % вже виданий',
            NEW.book_copy_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION sync_book_copy_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE book_copies
        SET status = 'borrowed'
        WHERE id = NEW.book_copy_id;

        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE'
       AND OLD.returned_at IS NULL
       AND NEW.returned_at IS NOT NULL THEN

        UPDATE book_copies
        SET status = 'available'
        WHERE id = NEW.book_copy_id;

        RETURN NEW;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loans_validate_before_insert
BEFORE INSERT ON loans
FOR EACH ROW
EXECUTE FUNCTION validate_loan_before_insert();

CREATE TRIGGER trg_loans_set_borrowed
AFTER INSERT ON loans
FOR EACH ROW
EXECUTE FUNCTION sync_book_copy_status();

CREATE TRIGGER trg_loans_set_available_after_return
AFTER UPDATE OF returned_at ON loans
FOR EACH ROW
WHEN (
    OLD.returned_at IS NULL
    AND NEW.returned_at IS NOT NULL
)
EXECUTE FUNCTION sync_book_copy_status();


