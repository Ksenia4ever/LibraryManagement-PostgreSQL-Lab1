CREATE OR REPLACE VIEW v_available_books AS
SELECT
    bc.id AS book_copy_id,
    b.id AS book_id,
    b.title,
    b.isbn,
    a.authors,
    g.name AS genre,
    p.name AS publisher,
    br.id AS branch_id,
    br.name AS branch_name,
    bc.barcode
FROM book_copies bc
JOIN books b
    ON b.id = bc.book_id
JOIN genres g
    ON g.id = b.genre_id
JOIN publishers p
    ON p.id = b.publisher_id
JOIN branches br
    ON br.id = bc.branch_id
LEFT JOIN LATERAL (
    SELECT STRING_AGG(
        au.first_name || ' ' || au.last_name,
        ', '
    ) AS authors
    FROM book_authors ba
    JOIN authors au
        ON au.id = ba.author_id
    WHERE ba.book_id = b.id
      AND au.is_deleted = false
) a ON true
WHERE bc.status = 'available'
  AND b.is_deleted = false
  AND br.is_deleted = false;

-- 12.2. Активні видачі
CREATE OR REPLACE VIEW v_active_loans AS
SELECT
    l.id AS loan_id,

    r.id AS reader_id,
    r.card_number,
    r.first_name || ' ' || r.last_name AS reader_name,

    b.id AS book_id,
    b.title,

    bc.id AS book_copy_id,
    bc.barcode,

    br.name AS branch_name,

    l.loaned_at,
    l.due_at,

    GREATEST(
        CURRENT_DATE - l.due_at::date,
        0
    ) AS days_overdue,

    e.first_name || ' ' || e.last_name AS issued_by
FROM loans l
JOIN readers r
    ON r.id = l.reader_id
JOIN book_copies bc
    ON bc.id = l.book_copy_id
JOIN books b
    ON b.id = bc.book_id
JOIN branches br
    ON br.id = bc.branch_id
JOIN employees e
    ON e.id = l.issued_by_employee_id
WHERE l.returned_at IS NULL;

-- 12.3. Історія видач читачів
CREATE OR REPLACE VIEW v_reader_loan_history AS
SELECT
    l.id AS loan_id,

    r.id AS reader_id,
    r.card_number,
    r.first_name || ' ' || r.last_name AS reader_name,

    b.id AS book_id,
    b.title,
    bc.barcode,

    l.loaned_at,
    l.due_at,
    l.returned_at,

    CASE
        WHEN l.returned_at IS NULL
            THEN 'active'
        ELSE 'returned'
    END AS loan_status,

    COALESCE(
        (
            SELECT SUM(f.amount)
            FROM fines f
            WHERE f.loan_id = l.id
              AND f.status <> 'cancelled'
        ),
        0
    ) AS total_fines
FROM loans l
JOIN readers r
    ON r.id = l.reader_id
JOIN book_copies bc
    ON bc.id = l.book_copy_id
JOIN books b
    ON b.id = bc.book_id;

