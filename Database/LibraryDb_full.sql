CREATE OR REPLACE FUNCTION set_audit_fields()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_user_id INTEGER;
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;

    BEGIN
        v_user_id :=
            NULLIF(current_setting('app.user_id', true), '')::INTEGER;
    EXCEPTION
        WHEN OTHERS THEN
            v_user_id := NULL;
    END;

    IF v_user_id IS NOT NULL THEN
        NEW.updated_by_user_id := v_user_id;
    END IF;

    RETURN NEW;
END;
$$;


