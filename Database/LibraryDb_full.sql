CREATE OR REPLACE PROCEDURE soft_delete_reader(
    p_reader_id INTEGER,
    p_user_id INTEGER
)
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM set_config('app.user_id', p_user_id::text, true);

    UPDATE readers
    SET
        is_deleted = true,
        deleted_at = CURRENT_TIMESTAMP
    WHERE id = p_reader_id
      AND is_deleted = false;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Reader with id % not found or already deleted',
            p_reader_id;
    END IF;
END;
$$;

