CREATE OR REPLACE FUNCTION calculate_overdue_fine(
    p_loan_id INTEGER,
    p_daily_rate NUMERIC(10,2) DEFAULT 10.00
)
RETURNS NUMERIC(10,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_due_at TIMESTAMP;
    v_returned_at TIMESTAMP;
    v_days_overdue INTEGER;
BEGIN
    SELECT
        due_at,
        returned_at
    INTO
        v_due_at,
        v_returned_at
    FROM loans
    WHERE id = p_loan_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Видачу з id % не знайдено',
            p_loan_id;
    END IF;

    v_days_overdue :=
        GREATEST(
            COALESCE(v_returned_at, CURRENT_TIMESTAMP)::date
            - v_due_at::date,
            0
        );

    RETURN v_days_overdue * p_daily_rate;
END;
$$;

CREATE OR REPLACE FUNCTION get_available_copies_count(
    p_book_id INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_count INTEGER;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM books
        WHERE id = p_book_id
          AND is_deleted = false
    ) THEN
        RAISE EXCEPTION
            'Активну книгу з id % не знайдено',
            p_book_id;
    END IF;

    SELECT COUNT(*)
    INTO v_count
    FROM book_copies bc
    JOIN branches br
        ON br.id = bc.branch_id
    WHERE bc.book_id = p_book_id
      AND bc.status = 'available'
      AND br.is_deleted = false;

    RETURN v_count;
END;
$$;


